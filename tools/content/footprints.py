# ---- 预先认准每首诗：课本 72 首里的记下序号 d；全唐诗 / 全宋诗索引里有的记下编号 c（需要 tools/.cache 里的 chinese-poetry 数据）；
#      其余（多为宋词）运行时在诗库里按 诗名 + 作者 + 首句 查找
import glob, re
ROOT = os.path.join(HERE, "..", "..")
CPD = os.path.join(ROOT, "tools", ".cache", "chinese-poetry-2.0.1", "package", "dist", "quantangshi")
def resolver():
    daily = json.load(open(os.path.join(ROOT, "site", "poem", "daily-poems.json"), encoding="utf-8"))["poems"]
    idx = json.load(open(os.path.join(ROOT, "site", "data", "cp", "index.json"), encoding="utf-8"))
    a = list(idx["t2s"]); t2s = {a[i]: a[i + 1] for i in range(0, len(a) - 1, 2)}
    ts = lambda x: "".join(t2s.get(c, c) for c in x)
    han = lambda x: "".join(c for c in x if "\u3400" <= c <= "\u9fff")
    rows = []
    for fn in sorted(glob.glob(os.path.join(ROOT, "site", "data", "cp", "t", "*.txt"))):
        for l in open(fn, encoding="utf-8"):
            i = l.index("\t"); rows.append((int(l[:i], 36), l[i + 1:].strip()))
    cache = {}
    def get(i):
        if i >= idx["songBase"]: k, fi, j = "song", (i - idx["songBase"]) // 1024, (i - idx["songBase"]) % 1024
        else: k, fi, j = "tang", i // 1024, i % 1024
        fn = os.path.join(CPD, f"poet.{k}.{fi * 1000}.json")
        if fn not in cache: cache[fn] = json.load(open(fn, encoding="utf-8")) if os.path.exists(fn) else []
        arr = cache[fn]; return arr[j] if j < len(arr) else None
    bt = lambda t: re.sub(r"[（(][^）)]*[）)]", "", t)
    def like(text, hint):
        h = han(hint); x = han(ts(text))[:len(h)]
        return h and sum(1 for p, q in zip(h, x) if p == q) >= max(2, len(h) * 0.6)
    def resolve(author, p):
        for i, d in enumerate(daily):
            if d["a"] == author and bt(d["t"]) == p["t"]: return {"d": i}
        if not os.path.isdir(CPD): return {}
        key = p.get("q") or p["t"].split("·")[0]
        best = None
        for i, t in rows:
            if key not in t: continue
            r = get(i)
            if not r or ts(r["author"]) != author or not like("".join(r["paragraphs"]), p.get("f", "")): continue
            score = (t == key) * 4 + t.startswith(key) * 2 - len(t) / 100
            if best is None or score > best[0]: best = (score, i)
        return {"c": best[1]} if best else {}
    return resolve

def main():
    res = resolver()
    miss = []
    for a, P in POETS.items():
        for s in P["stops"]:
            for p in s.get("poems", []):
                r = {} if p.get("x") else res(a, p); p.update(r)
                if not r and not p.get("x"): miss.append(a + "《" + p["t"] + "》")
    print("运行时在诗库里查找：", "、".join(miss))
    used = {s["p"] for p in POETS.values() for s in p["stops"]}
    places = {k: {"n": v[0], **({"m": v[1]} if v[1] else {}), "lat": v[2], "lng": v[3]} for k, v in PLACES.items() if k in used}
    data = {"note": "吟诗原创整理：只收较公认的行迹与作品归属，年份多为约数；地点按今城区近似经纬度落点。",
            "places": places, "poets": POETS}
    json.dump(data, open(OUT, "w", encoding="utf-8"), ensure_ascii=False, separators=(",", ":"))
    n = {k: (len(v["stops"]), len({s["p"] for s in v["stops"]}), sum(len(s.get("poems", [])) for s in v["stops"])) for k, v in POETS.items()}
    print(OUT, os.path.getsize(OUT), "bytes; places", len(places), n)

if __name__ == "__main__":
    main()
